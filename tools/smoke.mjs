import { createRequire } from 'module';
const require = createRequire('/workspace/keatland/tests/');
const { chromium } = require('playwright');
const url = process.argv[2] || 'http://localhost:4180/';
const out = process.argv[3] || 'screenshots/_smoke.png';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const logs = [];
page.on('console', (m) => logs.push(m.type() + ': ' + m.text()));
page.on('pageerror', (e) => logs.push('pageerror: ' + e.message));
const t0 = Date.now();
await page.goto(url);
await page.waitForFunction(() => window.__keatland?.ready, null, { timeout: 180000 }).catch((e) => logs.push('timeout ' + e.message));
console.log('ready in', (Date.now() - t0) / 1000, 's');
await page.evaluate(() => window.__keatland?.enter());
await page.waitForTimeout(6000);
console.log(await page.evaluate(() => JSON.stringify({ fps: window.__keatland?.fps, s: window.__keatland?.state, info: window.__keatland?.info() })));
await page.screenshot({ path: out });
console.log(logs.slice(0, 40).join('\n'));
await browser.close();
